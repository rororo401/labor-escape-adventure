def validate(variants: list[dict]) -> dict:
    hard_errors = []
    warnings = []
    ids = [row["id"] for row in variants]
    names = [row["name_ko"] for row in variants]
    scenes = [row["scene_ko"] for row in variants]
    summaries = [row["summary_ko"] for row in variants]
    bucket_counts = Counter(row["bucket_id"] for row in variants)
    if len(variants) != TARGET_TOTAL:
        hard_errors.append("expected %d variants, got %d" % (TARGET_TOTAL, len(variants)))
    if len(ids) != len(set(ids)):
        hard_errors.append("duplicate ids found")
    if len(names) != len(set(names)):
        hard_errors.append("duplicate names found")
    if len(scenes) != len(set(scenes)):
        hard_errors.append("duplicate scenes found")
    if len(summaries) != len(set(summaries)):
        hard_errors.append("duplicate summaries found")
    uneven = {bucket: count for bucket, count in bucket_counts.items() if count != CASES_PER_BUCKET}
    if uneven:
        hard_errors.append("bucket counts are not %d each: %s" % (CASES_PER_BUCKET, uneven))
    bad_dialogues = [
        row["id"]
        for row in variants
        if len(row["dialogue_ko"]) != 3 or len(set(row["dialogue_ko"])) != 3
    ]
    if bad_dialogues:
        hard_errors.append("dialogue count/uniqueness failed: %s" % bad_dialogues[:10])
    near_pairs = similar_name_pairs(names, threshold=0.82)
    if len(near_pairs) > 20:
        warnings.append("many similar title pairs: %d" % len(near_pairs))
    token_counts = Counter(token for name in names for token in tokenize(name))
    overused_tokens = [
        {"token": token, "count": count}
        for token, count in token_counts.most_common()
        if count >= 18 and token not in {"확인", "정리", "업무"}
    ]
    if overused_tokens:
        warnings.append("overused title tokens: %s" % overused_tokens[:10])
    return {
        "hard_errors": hard_errors,
        "warnings": warnings,
        "bucket_counts": dict(sorted(bucket_counts.items())),
        "tag_counts": dict(sorted(Counter(tag for row in variants for tag in row["tags"]).items())),
        "tone_counts": dict(sorted(Counter(row["tone"] for row in variants).items())),
        "similar_name_pairs_sample": near_pairs[:20],
        "overused_tokens": overused_tokens[:20],
    }


def tokenize(text: str) -> list[str]:
    return [token for token in re.split(r"\s+", text.strip()) if token]


def similar_name_pairs(names: list[str], threshold: float) -> list[dict]:
    pairs = []
    for i, left in enumerate(names):
        left_tokens = set(tokenize(left))
        if not left_tokens:
            continue
        for right in names[i + 1:]:
            right_tokens = set(tokenize(right))
            if not right_tokens:
                continue
            score = len(left_tokens & right_tokens) / len(left_tokens | right_tokens)
            if score >= threshold:
                pairs.append({"left": left, "right": right, "score": round(score, 3)})
    return pairs


def write_json(variants: list[dict], validation: dict) -> None:
    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(json.dumps({
        "version": 2,
        "purpose": "Text-only candidate catalog for 200 company work base variants, each with 3 dialogue variants.",
        "counts": {
            "total": len(variants),
            "bucket_count": len(set(row["bucket_id"] for row in variants)),
            "per_bucket": CASES_PER_BUCKET,
            "dialogue_per_event": 3,
            "dialogue_total": sum(len(row["dialogue_ko"]) for row in variants),
        },
        "validation": validation,
        "variants": variants,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def write_csv(variants: list[dict]) -> None:
    CSV_PATH.parent.mkdir(parents=True, exist_ok=True)
    with CSV_PATH.open("w", encoding="utf-8", newline="") as fp:
        writer = csv.DictWriter(fp, fieldnames=[
            "id", "name_ko", "bucket_id", "bucket_ko", "summary_ko", "scene_ko",
            "dialogue_1_ko", "dialogue_2_ko", "dialogue_3_ko",
            "tags", "tone", "cash_delta", "health_delta", "mood_delta", "fatigue_delta",
            "image_needed",
        ])
        writer.writeheader()
        for row in variants:
            out = row.copy()
            dialogues = out.pop("dialogue_ko")
            out["dialogue_1_ko"] = dialogues[0]
            out["dialogue_2_ko"] = dialogues[1]
            out["dialogue_3_ko"] = dialogues[2]
            for key in ["tags", "health_delta", "mood_delta", "fatigue_delta"]:
                out[key] = json.dumps(out[key], ensure_ascii=False)
            writer.writerow(out)


