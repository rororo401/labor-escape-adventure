def write_report(variants: list[dict], validation: dict) -> None:
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# 회사 기본업무 변주 다양성 검증 보고서",
        "",
        "## 결론",
        "",
    ]
    if validation["hard_errors"]:
        lines.append("200개 후보 구성에 하드 오류가 있다.")
    else:
        lines.append("회사 기본업무 후보는 200개로 압축했고, 각 이벤트마다 대사 3종을 붙여 텍스트 체감 반복을 줄이는 구조로 바꿨다.")
    lines.extend([
        "",
        "## 수량 검증",
        "",
        "| 항목 | 결과 |",
        "|---|---|",
        f"| 총 후보 | {len(variants)} |",
        f"| 업무 묶음 수 | {len(validation['bucket_counts'])} |",
        f"| 묶음별 후보 | {CASES_PER_BUCKET} |",
        f"| 전체 대사 줄 | {sum(len(row['dialogue_ko']) for row in variants)} |",
        f"| 중복 ID/이름/장면/요약 | {'없음' if not validation['hard_errors'] else '확인 필요'} |",
        "",
        "## 묶음별 분포",
        "",
        "| 묶음 | 수량 |",
        "|---|---:|",
    ])
    bucket_name = {bucket["id"]: bucket["name"] for bucket in BUCKETS}
    for bucket_id, count in validation["bucket_counts"].items():
        lines.append(f"| {bucket_name.get(bucket_id, bucket_id)} | {count} |")
    lines.extend([
        "",
        "## 태그 분포",
        "",
        "| 태그 | 수량 |",
        "|---|---:|",
    ])
    for tag, count in sorted(validation["tag_counts"].items(), key=lambda item: (-item[1], item[0])):
        lines.append(f"| `{tag}` | {count} |")
    lines.extend([
        "",
        "## 톤 분포",
        "",
        "| 톤 | 수량 |",
        "|---|---:|",
    ])
    for tone, count in validation["tone_counts"].items():
        lines.append(f"| `{tone}` | {count} |")
    lines.extend(["", "## 경고", ""])
    if validation["warnings"]:
        for warning in validation["warnings"]:
            lines.append(f"- {warning}")
    else:
        lines.append("- 없음")
    lines.extend(["", "## 비슷한 제목 샘플", ""])
    if validation["similar_name_pairs_sample"]:
        for pair in validation["similar_name_pairs_sample"]:
            lines.append(f"- {pair['left']} / {pair['right']} / {pair['score']}")
    else:
        lines.append("- 높은 유사도 제목 쌍 없음")
    lines.extend([
        "",
        "## 판단",
        "",
        "- 500개 조합식 후보는 사소한 행동이 많아졌기 때문에 실제 반영용으로는 과하다.",
        "- 200개 후보는 회사 업무로 인식되는 사건 단위만 남기고, 이벤트당 대사 3종으로 반복감을 줄이는 방향이다.",
        "- 다음 단계에서는 이 목록을 실제 `day_actions`의 회사 기본업무 풀로 승격하고, 출근일마다 1개를 고르는 로직을 연결하면 된다.",
        "- 이미지 제작은 아직 필수가 아니다. 기존 회사 배경/업무 CG를 공유하고 텍스트 변주를 먼저 적용하는 편이 용량과 작업량 면에서 안정적이다.",
    ])
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")


